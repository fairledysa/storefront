function normalizeSquareLinksWidthMode(
  value: unknown,
): "container" | "full_width" {
  const rawValue =
    value && typeof value === "object"
      ? (value as any).value ??
        (value as any).id ??
        (value as any).key ??
        (value as any).label ??
        ""
      : value;

  const normalized = s(rawValue).trim().toLowerCase();

  return [
    "full_width",
    "full-width",
    "full",
    "100%",
    "100",
    "100% من عرض الصفحة",
  ].includes(normalized)
    ? "full_width"
    : "container";
}

