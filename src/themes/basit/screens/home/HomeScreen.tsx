type ImageLinksGridLayout = "1" | "2" | "3" | "3_inline" | "4" | "4_inline";

function cleanAlt(value: unknown) {
  return s(value)
    .replace(/<[^>]*>/g, " ")
    .replace(/[|]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function imageAlt(...values: unknown[]) {
  for (const value of values) {
    const clean = cleanAlt(value);
    if (clean) return clean;
  }

  return "صورة";
}

function normalizeImageLinksGridLayout(value: unknown): ImageLinksGridLayout {
  const layout = s(value);

  if (layout === "1") return "1";
  if (layout === "3_inline") return "3_inline";
  if (layout === "4_inline") return "4_inline";
  if (layout === "4") return "4";
  if (layout === "3") return "3";

  return "2";
}

function getBooleanValue(value: any) {
  if (value === true) return true;
  if (value === false) return false;

  const text = s(value).toLowerCase();

  return (
    text === "true" ||
    text === "1" ||
    text === "yes" ||
    text === "on" ||
    text === "enabled"
  );
}

type HeroTextHorizontalPosition = "right" | "center" | "left";
type HeroTextVerticalPosition = "top" | "middle" | "bottom";
type HeroTextAlignment = "right" | "center" | "left";

function normalizeHeroTextHorizontalPosition(
  value: unknown,
): HeroTextHorizontalPosition {
  const normalized = s(value).trim().toLowerCase();

  if (["left", "يسار", "اليسار"].includes(normalized)) return "left";
  if (["center", "centre", "middle", "وسط", "الوسط"].includes(normalized)) {
    return "center";
  }

  return "right";
}

function normalizeHeroTextVerticalPosition(
  value: unknown,
): HeroTextVerticalPosition {
  const normalized = s(value).trim().toLowerCase();

  if (["top", "up", "أعلى", "اعلى", "فوق"].includes(normalized)) return "top";
  if (["bottom", "down", "أسفل", "اسفل", "تحت"].includes(normalized)) {
    return "bottom";
  }

  return "middle";
}

function normalizeHeroTextAlignment(value: unknown): HeroTextAlignment {
  const normalized = s(value).trim().toLowerCase();

  if (["left", "يسار", "اليسار"].includes(normalized)) return "left";
  if (["center", "centre", "middle", "وسط", "الوسط"].includes(normalized)) {
    return "center";
  }

  return "right";
}

