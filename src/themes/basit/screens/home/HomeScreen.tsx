function clampStoryNumber(
  value: unknown,
  minimum: number,
  maximum: number,
  fallback: number,
) {
  const parsed = Number(value);
  if (!Number.isFinite(parsed)) return fallback;
  return Math.min(maximum, Math.max(minimum, parsed));
}

function normalizeStoryCardSize(value: unknown): StoryCardSize {
  const normalized = s(value).trim().toLowerCase();
  if (["compact", "small", "صغيرة", "صغير"].includes(normalized)) {
    return "compact";
  }
  if (["large", "big", "كبيرة", "كبير"].includes(normalized)) {
    return "large";
  }
  return "medium";
}

